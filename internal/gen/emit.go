// renderModel renders the IR.
func renderModel(ir *IR) ([]byte, error) {
	data, err := json.MarshalIndent(ir, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

func goString(s string) string {
	return strconv.Quote(s)
}

func goStrings(list []string) string {
	q := make([]string, len(list))
	for i, s := range list {
		q[i] = goString(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

var goEncodings = map[string]string{ENC_PLAIN: "ENC_PLAIN", ENC_JSON: "ENC_JSON", ENC_REF: "ENC_REF", ENC_REF_BY: "ENC_REF_BY"}
var goTypes = map[string]string{TYPE_STRING: "ATTR_STRING", TYPE_INT64: "ATTR_INT64", TYPE_BOOL: "ATTR_BOOL", TYPE_FLOAT64: "ATTR_FLOAT64"}
var goModes = map[string]string{
	"":                     "MODE_NONE",
	MODE_REQUIRED:          "MODE_REQUIRED",
	MODE_OPTIONAL:          "MODE_OPTIONAL",
	MODE_COMPUTED:          "MODE_COMPUTED",
	MODE_OPTIONAL_COMPUTED: "MODE_OPTIONAL_COMPUTED",
}
var goDSModes = map[string]string{DS_FILTER: "DS_FILTER", DS_COMPUTED: "DS_COMPUTED"}

// renderGoSpecs renders the spec literals the provider registers.
func renderGoSpecs(specs []*Spec, o *Overrides) ([]byte, error) {
	var b bytes.Buffer
	w := func(format string, args ...any) { _, _ = fmt.Fprintf(&b, format, args...) }
	w("// Code generated by balena-schema generate from schema/model.json and schema/overrides.yaml. DO NOT EDIT.\n\n")
	w("package provider\n\n")
	w("// GENERATED_SPECS are the tables the provider exposes, in Terraform type name order.\n")
	w("var GENERATED_SPECS = []*TableSpec{\n")
	for _, s := range specs {
		w("{\n")
		w("TypeSuffix: %s,\n", goString(strings.TrimPrefix(s.TypeName, "balena_")))
		w("Table: %s,\n", goString(s.Table))
		w("Root: %s,\n", goString(s.Root))
		if s.Preview {
			w("Preview: true,\n")
		}
		if s.Resource {
			w("Resource: true,\n")
			w("ResourceDescription: %s,\n", goString(s.ResourceDescription))
		}
		if s.DataSource {
			w("DataSource: true,\n")
			w("DataSourceDescription: %s,\n", goString(s.DataSourceDescription))
		}
		if s.ImportBy != "" {
			w("ImportBy: %s,\n", goString(s.ImportBy))
		}
		if len(s.Hooks) > 0 {
			var hooks []string
			for _, step := range sortedKeys(s.Hooks) {
				hooks = append(hooks, strings.ToUpper(step[:1])+step[1:]+": "+s.Hooks[step])
			}
			w("Hooks: TableHooks{%s},\n", strings.Join(hooks, ", "))
		}
		w("Attributes: []*AttributeSpec{\n")
		for _, a := range s.Attributes {
			fields := []string{
				"Name: " + goString(a.Name),
				"Field: " + goString(a.Field),
				"Type: " + goTypes[a.Type],
				"Encoding: " + goEncodings[a.Encoding],
			}
			if a.RefTable != "" {
				fields = append(fields, "RefTable: "+goString(a.RefTable))
			}
			if a.RefField != "" {
				fields = append(fields, "RefField: "+goString(a.RefField))
			}
			if a.Resolver != "" {
				fields = append(fields, "Resolver: "+a.Resolver)
			}
			fields = append(fields, "Resource: "+goModes[a.ResourceMode], "DataSource: "+goDSModes[a.DataSourceMode])
			if a.ForceNew {
				fields = append(fields, "ForceNew: true")
			}
			if a.Sensitive {
				fields = append(fields, "Sensitive: true")
			}
			if a.Stable {
				fields = append(fields, "Stable: true")
			}
			if a.MinLength > 0 {
				fields = append(fields, "MinLength: "+strconv.Itoa(a.MinLength))
			}
			if a.MaxLength > 0 {
				fields = append(fields, "MaxLength: "+strconv.Itoa(a.MaxLength))
			}
			if len(a.OneOf) > 0 {
				fields = append(fields, "OneOf: "+goStrings(a.OneOf))
			}
			if v := a.VarName; v != nil {
				parts := []string{"Invalid: " + goString(v.Invalid)}
				if len(v.Reserved) > 0 {
					parts = append(parts, "Reserved: "+goStrings(v.Reserved))
				}
				if len(v.RequiredPrefixes) > 0 {
					parts = append(parts, "RequiredPrefixes: "+goStrings(v.RequiredPrefixes))
				}
				if len(v.ForbiddenPrefixes) > 0 {
					parts = append(parts, "ForbiddenPrefixes: "+goStrings(v.ForbiddenPrefixes))
				}
				fields = append(fields, "VarName: &VarNameRule{"+strings.Join(parts, ", ")+"}")
			}
			fields = append(fields, "Description: "+goString(a.Description))
			w("{%s},\n", strings.Join(fields, ", "))
		}
		w("},\n")
		w("},\n")
	}
	w("}\n\n")
	w("// GENERATED_HOOK_USES lists, per hook, the API columns (\"<table>.<field>\") schema/overrides.yaml declares it uses.\n")
	w("var GENERATED_HOOK_USES = map[string][]string{\n")
	for _, name := range sortedKeys(o.Hooks) {
		uses := append([]string{}, o.Hooks[name].Uses...)
		sort.Strings(uses)
		w("%s: %s,\n", goString(name), goStrings(uses))
	}
	w("}\n")
	return format.Source(b.Bytes())
}

// Baseline is the coverage of the hand-written provider before generation, as measured in the feasibility analysis.
var BASELINE = []string{
	"open-balena-api model (resin): 24 of 48 tables, 106 of 379 columns",
	"balena-cloud /v7 (balena-sdk typings): 20 of 74 tables, 90 of 488 columns",
}

// renderCoverage renders the gap report.
func renderCoverage(ir *IR, specs []*Spec) []byte {
	var b bytes.Buffer
	w := func(format string, args ...any) { _, _ = fmt.Fprintf(&b, format, args...) }
	bySpec := map[string]*Spec{}
	for _, s := range specs {
		bySpec[s.Table] = s
	}
	counts := map[string]int{}
	for _, t := range ir.Tables {
		counts[t.Class.Status]++
	}
	w("<!-- Code generated by balena-schema generate. DO NOT EDIT. -->\n\n")
	w("# Coverage\n\n")
	w("Every table of the pinned models and what the generator does with it. Default root `/%s`; tables only the unversioned model has use `/resin` and are marked preview.\n\n", ir.DefaultRoot)
	w("## Summary\n\n")
	w("| Status | Tables |\n| --- | ---: |\n")
	for _, st := range []string{STATUS_GENERATED, STATUS_HANDWRITTEN, STATUS_EXCLUDED, STATUS_UNSCOPED} {
		w("| %s | %d |\n", st, counts[st])
	}
	w("| total | %d |\n\n", len(ir.Tables))

	// Column coverage against both models, measured like the baseline: distinct non-alias columns.
	for _, root := range ir.Roots {
		tables, cols, coveredTables, coveredCols := 0, 0, 0, 0
		for name, t := range ir.byRoot[root.Name] {
			tables++
			cols += len(t.Fields)
			s := bySpec[name]
			if s == nil {
				continue
			}
			coveredTables++
			exposed := map[string]bool{}
			for _, a := range s.Attributes {
				exposed[a.Field] = true
			}
			for _, f := range t.Fields {
				if exposed[f.Name] {
					coveredCols++
				}
			}
		}
		w("- `/%s` (`%s`): the provider covers %d of %d tables and %d of %d columns.\n", root.Name, root.Shape, coveredTables, tables, coveredCols, cols)
	}
	w("- Baseline before generation: %s.\n\n", strings.Join(BASELINE, "; "))

	w("## Tables\n\n")
	w("| Table | Root | Provenance | Status | Terraform | Reason |\n| --- | --- | --- | --- | --- | --- |\n")
	for _, t := range ir.Tables {
		c := t.Class
		var kinds []string
		if c.Status != STATUS_EXCLUDED {
			if c.Resource {
				kinds = append(kinds, "resource")
			}
			if c.DataSource {
				kinds = append(kinds, "data source")
			}
		}
		tf := "-"
		if len(kinds) > 0 {
			tf = "`" + c.TypeName + "` (" + strings.Join(kinds, ", ") + ")"
		}
		w("| `%s` | %s | %s | %s | %s | %s |\n", t.Name, t.Root, t.Provenance, c.Status, tf, escapeCell(c.Reason))
	}
	w("\n## Columns of in-scope tables\n\n")
	for _, s := range specs {
		t := ir.Table(s.Table)
		w("### `%s`\n\n", s.TypeName)
		w("`/%s/%s`, %d of %d columns.\n\n", s.Root, s.Table, len(s.Attributes), len(t.Fields))
		w("| Attribute | API field | Type | Resource | Data source |\n| --- | --- | --- | --- | --- |\n")
		for _, a := range s.Attributes {
			field := a.Field
			switch a.Encoding {
			case ENC_REF_BY:
				field += " → " + a.RefTable + "." + a.RefField
			case ENC_REF:
				field += " → " + a.RefTable
			}
			res := a.ResourceMode
			if res == "" {
				res = "-"
			}
			var flags []string
			if a.ForceNew {
				flags = append(flags, "forces replacement")
			}
			if a.Sensitive {
				flags = append(flags, "sensitive")
			}
			if len(flags) > 0 {
				res += " (" + strings.Join(flags, ", ") + ")"
			}
			w("| `%s` | `%s` | %s | %s | %s |\n", a.Name, field, a.Type, res, a.DataSourceMode)
		}
		for _, sk := range s.Skipped {
			w("| - | `%s` | - | skipped: %s | - |\n", sk.Field, escapeCell(sk.Reason))
		}
		if len(t.Unenforced) > 0 {
			w("\nSBVR necessities the provider does not check before apply (the API enforces them):\n\n")
			for _, n := range t.Unenforced {
				w("- %s\n", escapeCell(n))
			}
		}
		w("\n")
	}
	return b.Bytes()
}

func escapeCell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ")
}
