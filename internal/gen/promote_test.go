// writeFixture writes the synthetic repository with the given v8 model (and v8 SBVR, when not empty), generates it
// with v7 as the default root, and returns its directory.
func writeFixture(t *testing.T, v8ts, v8sbvr string) string {
	t.Helper()
	dir := t.TempDir()
	type file struct{ source, path, role, content string }
	files := []file{
		{sources.SOURCE_OPEN_BALENA_API, "src/balena-model.ts", sources.ROLE_SHAPE, FIXTURE_RESIN_TS},
		{sources.SOURCE_OPEN_BALENA_API, "src/balena.sbvr", sources.ROLE_CONSTRAINTS, FIXTURE_SBVR},
		{sources.SOURCE_OPEN_BALENA_API, "src/translations/v7/v7.sbvr", sources.ROLE_CONSTRAINTS, FIXTURE_SBVR},
		{sources.SOURCE_OPEN_BALENA_API, "src/lib/auth.ts", sources.ROLE_PERMISSIONS, FIXTURE_AUTH},
		{sources.SOURCE_BALENA_SDK, "src/types/v7.ts", sources.ROLE_SHAPE, FIXTURE_CLOUD_TS},
		{sources.SOURCE_BALENA_CLOUD, "config/vars", sources.ROLE_CONFIG_VARS, FIXTURE_CONFIG_VARS},
	}
	resinSBVR := sources.Ref(sources.SOURCE_OPEN_BALENA_API, "src/balena.sbvr")
	roots := []sources.Root{
		{Name: "resin", Shape: sources.Ref(sources.SOURCE_OPEN_BALENA_API, "src/balena-model.ts"), Constraints: []string{resinSBVR}, Preview: true},
		{Name: "v7", Shape: sources.Ref(sources.SOURCE_BALENA_SDK, "src/types/v7.ts"),
			Constraints: []string{resinSBVR, sources.Ref(sources.SOURCE_OPEN_BALENA_API, "src/translations/v7/v7.sbvr")}},
	}
	if v8ts != "" {
		files = append(files, file{sources.SOURCE_BALENA_SDK, "src/types/v8.ts", sources.ROLE_SHAPE, v8ts})
		v8 := sources.Root{Name: "v8", Shape: sources.Ref(sources.SOURCE_BALENA_SDK, "src/types/v8.ts"), Constraints: []string{resinSBVR}}
		if v8sbvr != "" {
			files = append(files, file{sources.SOURCE_OPEN_BALENA_API, "src/translations/v8/v8.sbvr", sources.ROLE_CONSTRAINTS, v8sbvr})
			v8.Constraints = append(v8.Constraints, sources.Ref(sources.SOURCE_OPEN_BALENA_API, "src/translations/v8/v8.sbvr"))
		}
		roots = append(roots, v8)
	}
	lock := &sources.Lock{Format: sources.LOCK_FORMAT, DefaultRoot: "v7", Roots: roots}
	bySource := map[string]*sources.Source{}
	for _, name := range []string{sources.SOURCE_OPEN_BALENA_API, sources.SOURCE_BALENA_SDK} {
		bySource[name] = &sources.Source{Name: name, Repo: "balena-io/" + name, Tag: "v1.0.0", Commit: strings.Repeat("1", 40), License: "test"}
	}
	bySource[sources.SOURCE_BALENA_CLOUD] = &sources.Source{Name: sources.SOURCE_BALENA_CLOUD, URL: "https://example.invalid/config/vars", License: "test"}
	for _, f := range files {
		local := sources.UPSTREAM_DIR + "/" + f.source + "/" + f.path
		writeFile(t, dir, local, f.content)
		src := bySource[f.source]
		src.Files = append(src.Files, sources.File{Path: f.path, Local: local, Role: f.role, SHA256: sources.Sha256Hex([]byte(f.content))})
	}
	for _, s := range bySource {
		lock.Sources = append(lock.Sources, *s)
	}
	data, err := lock.Marshal()
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, dir, sources.LOCK_PATH, string(data))
	writeFile(t, dir, OVERRIDES_PATH, FIXTURE_OVERRIDES)
	writeFile(t, dir, HOOKS_DIR+"/doc.go", "package provider\n")
	res, err := Generate(dir)
	if err != nil {
		t.Fatalf("fixture does not generate: %v", err)
	}
	if err := res.Write(dir); err != nil {
		t.Fatal(err)
	}
	return dir
}

func writeFile(t *testing.T, dir, rel, content string) {
	t.Helper()
	p := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// fakeContract runs the real contract checks against a fake API that answers 200 to everything except the paths in
// fail, which answer 401 as Pine.js does for an unknown table or column.
func fakeContract(t *testing.T, fail ...string) ContractRunner {
	return func(res *Result) ([]*ContractCheck, error) {
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			for _, f := range fail {
				if r.URL.Path == f {
					w.WriteHeader(http.StatusUnauthorized)
					return
				}
			}
			_, _ = w.Write([]byte(`{"d":[]}`))
		}))
		defer srv.Close()
		checks := ContractChecks(res.IR, res.Specs, res.Overrides)
		RunContract(context.Background(), balena.NewClient(srv.URL, "t", "test", balena.WithMaxRetries(0)), checks)
		return checks, nil
	}
}

