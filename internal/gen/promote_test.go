func TestPromotionPlans(t *testing.T) {
	tests := []struct {
		name          string
		v8ts, v8sbvr  string
		fail          []string
		status, level string
		fallbacks     string
		change        string
	}{
		{
			name: "no newer root", status: PROMOTION_NONE,
		},
		{
			name: "additive", v8ts: V8_ADDITIVE, status: PROMOTION_READY, level: LEVEL_FEAT,
			change: "resource balena_application.description added",
		},
		{
			name: "breaking rename", v8ts: V8_RENAMED, v8sbvr: V8_RENAMED_SBVR, status: PROMOTION_READY, level: LEVEL_BREAKING,
			change: "resource balena_application.app_name removed",
		},
		{
			name: "table missing in the new root falls back to /resin", v8ts: V8_NO_TAGS, v8sbvr: V8_NO_TAGS_SBVR,
			status: PROMOTION_READY, level: LEVEL_FEAT, fallbacks: "application_tag (served from /resin)",
			change: "resource balena_application_tag moves from /v7/application_tag to /resin/application_tag",
		},
		{
			name: "contract failure blocks", v8ts: V8_ADDITIVE, fail: []string{"/v8/application"}, status: PROMOTION_BLOCKED,
		},
		{
			name: "a root that does not cross-check blocks", v8ts: V8_RENAMED, status: PROMOTION_BLOCKED,
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			dir := writeFixture(t, tc.v8ts, tc.v8sbvr)
			plan, err := PlanPromotion(dir, "", fakeContract(t, tc.fail...))
			if err != nil {
				t.Fatal(err)
			}
			if plan.Status != tc.status || plan.Current != "v7" {
				t.Fatalf("plan = %+v, want status %s", plan, tc.status)
			}
			if tc.level != "" && plan.Level != tc.level {
				t.Errorf("level = %s, want %s; changes %v", plan.Level, tc.level, plan.Changes)
			}
			if got := strings.Join(plan.Fallbacks, ", "); got != tc.fallbacks {
				t.Errorf("fallbacks = %q, want %q", got, tc.fallbacks)
			}
			if tc.change != "" {
				found := false
				for _, c := range plan.Changes {
					found = found || c.Message == tc.change
				}
				if !found {
					t.Errorf("changes %v lack %q", plan.Changes, tc.change)
				}
			}
			if tc.status == PROMOTION_BLOCKED {
				if !strings.Contains(plan.Markdown(), "was **not** promoted") {
					t.Errorf("a blocked plan must say so: %s", plan.Markdown())
				}
				if err := ApplyPromotion(dir, plan); err == nil {
					t.Errorf("a blocked plan must not apply")
				}
				if lock, _ := sources.ReadLock(dir); lock.DefaultRoot != "v7" {
					t.Errorf("default root changed to %s", lock.DefaultRoot)
				}
			}
			if len(tc.fail) > 0 && len(plan.ContractFailures) == 0 {
				t.Errorf("contract failures not reported")
			}
		})
	}
}

// TestApplyPromotion promotes v8 and checks that the repository regenerates for it and still passes the offline
// gates, with names kept from the surface lock.
func TestApplyPromotion(t *testing.T) {
	dir := writeFixture(t, V8_ADDITIVE, "")
	plan, err := PlanPromotion(dir, "", fakeContract(t))
	if err != nil || plan.Status != PROMOTION_READY {
		t.Fatalf("plan = %+v, %v", plan, err)
	}
	if err := ApplyPromotion(dir, plan); err != nil {
		t.Fatal(err)
	}
	if plan.Status != PROMOTION_DONE || !strings.Contains(plan.Markdown(), "promoted `/v8`") {
		t.Errorf("plan after apply = %+v", plan)
	}
	lock, err := sources.ReadLock(dir)
	if err != nil || lock.DefaultRoot != "v8" {
		t.Fatalf("default root = %v, %v", lock, err)
	}
	res, err := Generate(dir)
	if err != nil {
		t.Fatal(err)
	}
	if stale := res.Stale(dir); len(stale) > 0 {
		t.Errorf("stale after promotion: %v", stale)
	}
	app := res.Surface.Resources["balena_application"]
	if app.Root != "v8" || app.Attributes["description"] == nil || app.Attributes["app_name"] == nil {
		t.Errorf("balena_application after promotion = %+v", app)
	}
	// Nothing newer is left, so planning again is a no-op.
	if again, err := PlanPromotion(dir, "", fakeContract(t)); err != nil || again.Status != PROMOTION_NONE {
		t.Errorf("second plan = %+v, %v", again, err)
	}
}

// TestPromotionWhenTheCurrentRootBreaks covers upstream breaking the current root: the plan compares against the
// committed surface and still promotes a working newer root.
func TestPromotionWhenTheCurrentRootBreaks(t *testing.T) {
	dir := writeFixture(t, V8_ADDITIVE, "")
	// Break v7: its SBVR now has a column its model lacks.
	broken := FIXTURE_SBVR + "Fact type: organization has app name\n\tNecessity: each organization has at most one app name.\n"
	local := sources.UPSTREAM_DIR + "/" + sources.SOURCE_OPEN_BALENA_API + "/src/translations/v7/v7.sbvr"
	writeFile(t, dir, local, broken)
	lock, err := sources.ReadLock(dir)
	if err != nil {
		t.Fatal(err)
	}
	for i := range lock.Sources {
		for j := range lock.Sources[i].Files {
			if lock.Sources[i].Files[j].Local == local {
				lock.Sources[i].Files[j].SHA256 = sources.Sha256Hex([]byte(broken))
			}
		}
	}
	data, err := lock.Marshal()
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, dir, sources.LOCK_PATH, string(data))
	if _, err := Generate(dir); err == nil {
		t.Fatal("the broken v7 should not generate")
	}
	plan, err := PlanPromotion(dir, "", fakeContract(t))
	if err != nil {
		t.Fatal(err)
	}
	if plan.Status != PROMOTION_READY || plan.CurrentError == "" {
		t.Errorf("plan = %+v", plan)
	}
}
