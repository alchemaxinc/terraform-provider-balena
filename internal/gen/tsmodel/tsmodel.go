// Package tsmodel parses the TypeScript model files that @balena/abstract-sql-to-typescript generates (open-balena-api
// src/balena-model.ts, balena-sdk src/types/v7.ts) into a typed model. The input is untrusted data: the parser only
// accepts the small, regular subset of TypeScript those files use and fails on anything else.
package tsmodel

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Kind is the kind of a model field.
type Kind string

const (
	// KIND_SCALAR is a primitive column such as Types['Short Text'].
	KIND_SCALAR Kind = "scalar"
	// KIND_ENUM is a column restricted to string literals.
	KIND_ENUM Kind = "enum"
	// KIND_FK is a reference to another resource.
	KIND_FK Kind = "fk"
	// KIND_REVERSE is a reverse navigation (one-to-many), not a column.
	KIND_REVERSE Kind = "reverse"
)

// Field is one field of the Read or Write shape of a resource.
type Field struct {
	Name     string
	Optional bool
	Kind     Kind
	Type     string
	Enum     []string
	Target   string
	Nullable bool
	// Experimental marks a field the SDK documents as "@experimental ... not part of the model". Such fields use plain
	// TypeScript types and are not columns.
	Experimental bool
}

// Interface is one exported resource interface.
type Interface struct {
	Name  string
	Read  []Field
	Write []Field
}

// ReadField returns the named Read field.
func (i *Interface) ReadField(name string) (Field, bool) {
	for _, f := range i.Read {
		if f.Name == name {
			return f, true
		}
	}
	return Field{}, false
}

// WriteField returns the named Write field.
func (i *Interface) WriteField(name string) (Field, bool) {
	for _, f := range i.Write {
		if f.Name == name {
			return f, true
		}
	}
	return Field{}, false
}

// Model is a parsed TypeScript model.
type Model struct {
	GeneratorVersion string
	Interfaces       map[string]*Interface
	// Canonical maps a canonical resource name (e.g. application__has__env_var_name) to its interface.
	Canonical map[string]string
	// Synonyms maps a synonym resource name (e.g. application_environment_variable) to its interface.
	Synonyms map[string]string
}

// ResourceName returns the name a resource is addressed by: its synonym (term form) when it has exactly one,
// otherwise its canonical name.
func (m *Model) ResourceName(iface string) (string, bool) {
	var syn []string
	for name, target := range m.Synonyms {
		if target == iface {
			syn = append(syn, name)
		}
	}
	sort.Strings(syn)
	if len(syn) == 1 {
		return syn[0], true
	}
	for name, target := range m.Canonical {
		if target == iface {
			return name, true
		}
	}
	return "", false
}

// CanonicalName returns the canonical $Model key of an interface.
func (m *Model) CanonicalName(iface string) string {
	for name, target := range m.Canonical {
		if target == iface {
			return name
		}
	}
	return ""
}

var (
	HEADER_RE         = regexp.MustCompile(`(?m)^// These types were generated by @balena/abstract-sql-to-typescript (v[0-9][0-9A-Za-z.+-]*)$`)
	INTERFACE_RE      = regexp.MustCompile(`^export interface ([A-Za-z][A-Za-z0-9]*) \{$`)
	MODEL_RE          = regexp.MustCompile(`^export default interface \$Model \{$`)
	MODEL_ENTRY_RE    = regexp.MustCompile(`^\t([a-z][a-z0-9_]*): ([A-Za-z][A-Za-z0-9]*);$`)
	FIELD_RE          = regexp.MustCompile(`^([A-Za-z_][A-Za-z0-9_]*)(\?)?:\s*(.+)$`)
	TYPES_RE          = regexp.MustCompile(`^Types\['([A-Za-z ]+)'\]\['(Read|Write)'\]$`)
	FK_READ_RE        = regexp.MustCompile(`^\{ __id: ([A-Za-z][A-Za-z0-9]*)\['Read'\]\['id'\] \}$`)
	FK_EXPANDED_RE    = regexp.MustCompile(`^\[([A-Za-z][A-Za-z0-9]*)\['Read'\]\]$`)
	FK_WRITE_RE       = regexp.MustCompile(`^([A-Za-z][A-Za-z0-9]*)\['Write'\]\['id'\]$`)
	REVERSE_RE        = regexp.MustCompile(`^Array<\s*([A-Za-z][A-Za-z0-9]*)\['Read'\]\s*>$`)
	LITERAL_RE        = regexp.MustCompile(`^'([^'\\]*)'$`)
	DOC_COMMENT_RE    = regexp.MustCompile(`(?s)^/\*\*(.*?)\*/\s*`)
	PLAIN_TYPES       = map[string]string{"boolean": "Boolean", "string": "Text", "number": "Integer"}
	WRITE_NEVER       = "Write: Record<string, never>;"
	IMPORT_LINE       = "import type { Types } from '@balena/abstract-sql-to-typescript';"
	MAX_FIELD_TYPE_SZ = 2000
)

// Parse parses a model file.
func Parse(src string) (*Model, error) {
	src = strings.ReplaceAll(src, "\r\n", "\n")
	m := &Model{
		Interfaces: map[string]*Interface{},
		Canonical:  map[string]string{},
		Synonyms:   map[string]string{},
	}
	if hm := HEADER_RE.FindStringSubmatch(src); hm != nil {
		m.GeneratorVersion = hm[1]
	} else {
		return nil, fmt.Errorf("missing abstract-sql-to-typescript header")
	}
	lines := strings.Split(src, "\n")
	for i := 0; i < len(lines); i++ {
		line := lines[i]
		switch {
		case line == "" || strings.HasPrefix(line, "//") || line == IMPORT_LINE:
			continue
		case INTERFACE_RE.MatchString(line):
			name := INTERFACE_RE.FindStringSubmatch(line)[1]
			end := closingLine(lines, i)
			if end < 0 {
				return nil, fmt.Errorf("line %d: interface %s is not closed", i+1, name)
			}
			iface, err := parseInterface(name, lines[i+1:end], i+2)
			if err != nil {
				return nil, err
			}
			if _, dup := m.Interfaces[name]; dup {
				return nil, fmt.Errorf("line %d: duplicate interface %s", i+1, name)
			}
			m.Interfaces[name] = iface
			i = end
		case MODEL_RE.MatchString(line):
			end := closingLine(lines, i)
			if end < 0 {
				return nil, fmt.Errorf("line %d: $Model is not closed", i+1)
			}
			synonyms := false
			for j := i + 1; j < end; j++ {
				l := lines[j]
				if strings.TrimSpace(l) == "// Synonyms" {
					synonyms = true
					continue
				}
				em := MODEL_ENTRY_RE.FindStringSubmatch(l)
				if em == nil {
					return nil, fmt.Errorf("line %d: unexpected $Model entry %q", j+1, l)
				}
				target := m.Canonical
				if synonyms {
					target = m.Synonyms
				}
				if _, dup := target[em[1]]; dup {
					return nil, fmt.Errorf("line %d: duplicate $Model entry %s", j+1, em[1])
				}
				target[em[1]] = em[2]
			}
			i = end
		default:
			return nil, fmt.Errorf("line %d: unexpected top-level content %q", i+1, truncate(line))
		}
	}
	if len(m.Canonical) == 0 {
		return nil, fmt.Errorf("no $Model interface found")
	}
	for name, iface := range m.Canonical {
		if _, ok := m.Interfaces[iface]; !ok {
			return nil, fmt.Errorf("$Model entry %s refers to unknown interface %s", name, iface)
		}
	}
	for name, iface := range m.Synonyms {
		if _, ok := m.Interfaces[iface]; !ok {
			return nil, fmt.Errorf("$Model synonym %s refers to unknown interface %s", name, iface)
		}
	}
	for _, iface := range m.Interfaces {
		for _, f := range append(append([]Field{}, iface.Read...), iface.Write...) {
			if f.Target != "" {
				if _, ok := m.Interfaces[f.Target]; !ok {
					return nil, fmt.Errorf("%s.%s refers to unknown interface %s", iface.Name, f.Name, f.Target)
				}
			}
		}
	}
	return m, nil
}

func truncate(s string) string {
	if len(s) > 80 {
		return s[:80] + "..."
	}
	return s
}

// closingLine returns the index of the line that is exactly "}" after start.
func closingLine(lines []string, start int) int {
	for j := start + 1; j < len(lines); j++ {
		if lines[j] == "}" {
			return j
		}
	}
	return -1
}

func parseInterface(name string, body []string, firstLine int) (*Interface, error) {
	iface := &Interface{Name: name}
	seenRead, seenWrite := false, false
	for i := 0; i < len(body); i++ {
		line := body[i]
		switch {
		case line == "\tRead: {" || line == "\tWrite: {":
			end := -1
			for j := i + 1; j < len(body); j++ {
				if body[j] == "\t};" {
					end = j
					break
				}
			}
			if end < 0 {
				return nil, fmt.Errorf("line %d: %s section of %s is not closed", firstLine+i, strings.TrimSpace(line), name)
			}
			section := "Read"
			if strings.HasPrefix(line, "\tWrite") {
				section = "Write"
			}
			fields, err := parseFields(strings.Join(body[i+1:end], "\n"), section)
			if err != nil {
				return nil, fmt.Errorf("interface %s %s: %w", name, section, err)
			}
			if section == "Read" {
				if seenRead {
					return nil, fmt.Errorf("interface %s has two Read sections", name)
				}
				seenRead = true
				iface.Read = fields
			} else {
				if seenWrite {
					return nil, fmt.Errorf("interface %s has two Write sections", name)
				}
				seenWrite = true
				iface.Write = fields
			}
			i = end
		case strings.TrimSpace(line) == WRITE_NEVER:
			if seenWrite {
				return nil, fmt.Errorf("interface %s has two Write sections", name)
			}
			seenWrite = true
		case strings.TrimSpace(line) == "":
			continue
		default:
			return nil, fmt.Errorf("line %d: unexpected content in interface %s: %q", firstLine+i, name, truncate(line))
		}
	}
	if !seenRead || !seenWrite {
		return nil, fmt.Errorf("interface %s lacks a Read or Write section", name)
	}
	return iface, nil
}

// parseFields splits a section body into `name?: type` statements at depth 0 and classifies each.
func parseFields(body, section string) ([]Field, error) {
	var stmts []string
	depth := 0
	var cur strings.Builder
	for _, ch := range body {
		switch ch {
		case '{', '[', '<', '(':
			depth++
		case '}', ']', '>', ')':
			depth--
			if depth < 0 {
				return nil, fmt.Errorf("unbalanced brackets")
			}
		}
		if ch == ';' && depth == 0 {
			if s := strings.TrimSpace(cur.String()); s != "" {
				stmts = append(stmts, s)
			}
			cur.Reset()
			continue
		}
		cur.WriteRune(ch)
	}
	if strings.TrimSpace(cur.String()) != "" || depth != 0 {
		return nil, fmt.Errorf("trailing or unbalanced content %q", truncate(cur.String()))
	}
	seen := map[string]bool{}
	fields := make([]Field, 0, len(stmts))
	for _, stmt := range stmts {
		experimental := false
		if cm := DOC_COMMENT_RE.FindStringSubmatch(stmt); cm != nil {
			if !strings.Contains(cm[1], "@experimental") {
				return nil, fmt.Errorf("unexpected doc comment %q", truncate(cm[0]))
			}
			experimental = true
			stmt = stmt[len(cm[0]):]
		}
		fm := FIELD_RE.FindStringSubmatch(strings.Join(strings.Fields(stmt), " "))
		if fm == nil {
			return nil, fmt.Errorf("cannot parse field %q", truncate(stmt))
		}
		if len(fm[3]) > MAX_FIELD_TYPE_SZ {
			return nil, fmt.Errorf("field %s: type too long", fm[1])
		}
		var f Field
		var err error
		if plain, ok := PLAIN_TYPES[fm[3]]; ok && experimental {
			f = Field{Name: fm[1], Optional: fm[2] == "?", Kind: KIND_SCALAR, Type: plain}
		} else if f, err = classify(fm[1], fm[2] == "?", fm[3], section); err != nil {
			return nil, err
		}
		f.Experimental = experimental
		if seen[f.Name] {
			return nil, fmt.Errorf("duplicate field %s", f.Name)
		}
		seen[f.Name] = true
		fields = append(fields, f)
	}
	return fields, nil
}

// splitUnion splits a type at top-level `|`, dropping a leading `|`.
func splitUnion(t string) []string {
	var out []string
	depth := 0
	var cur strings.Builder
	for _, ch := range t {
		switch ch {
		case '{', '[', '<', '(':
			depth++
		case '}', ']', '>', ')':
			depth--
		}
		if ch == '|' && depth == 0 {
			if s := strings.TrimSpace(cur.String()); s != "" {
				out = append(out, s)
			}
			cur.Reset()
			continue
		}
		cur.WriteRune(ch)
	}
	if s := strings.TrimSpace(cur.String()); s != "" {
		out = append(out, s)
	}
	return out
}

func classify(name string, optional bool, typ, section string) (Field, error) {
	f := Field{Name: name, Optional: optional}
	if rm := REVERSE_RE.FindStringSubmatch(typ); rm != nil {
		if section != "Read" || !optional {
			return f, fmt.Errorf("field %s: unexpected navigation outside an optional Read field", name)
		}
		f.Kind = KIND_REVERSE
		f.Target = rm[1]
		return f, nil
	}
	var fkRead, fkExpanded, fkWrite, scalar string
	var literals []string
	for _, alt := range splitUnion(typ) {
		switch {
		case alt == "null":
			f.Nullable = true
		case alt == "[]":
			// An empty expansion of a nullable reference.
		case FK_READ_RE.MatchString(alt):
			fkRead = FK_READ_RE.FindStringSubmatch(alt)[1]
		case FK_EXPANDED_RE.MatchString(alt):
			fkExpanded = FK_EXPANDED_RE.FindStringSubmatch(alt)[1]
		case FK_WRITE_RE.MatchString(alt):
			fkWrite = FK_WRITE_RE.FindStringSubmatch(alt)[1]
		case TYPES_RE.MatchString(alt):
			tm := TYPES_RE.FindStringSubmatch(alt)
			if tm[2] != section {
				return f, fmt.Errorf("field %s: %s type in %s section", name, tm[2], section)
			}
			if scalar != "" {
				return f, fmt.Errorf("field %s: two scalar types", name)
			}
			scalar = tm[1]
		case LITERAL_RE.MatchString(alt):
			literals = append(literals, LITERAL_RE.FindStringSubmatch(alt)[1])
		default:
			return f, fmt.Errorf("field %s: unsupported type alternative %q", name, truncate(alt))
		}
	}
	kinds := 0
	for _, present := range []bool{fkRead != "" || fkExpanded != "", fkWrite != "", scalar != "", len(literals) > 0} {
		if present {
			kinds++
		}
	}
	if kinds != 1 {
		return f, fmt.Errorf("field %s: ambiguous type %q", name, truncate(typ))
	}
	switch {
	case fkRead != "" || fkExpanded != "":
		if section != "Read" || fkRead == "" || fkRead != fkExpanded {
			return f, fmt.Errorf("field %s: malformed reference type %q", name, truncate(typ))
		}
		f.Kind = KIND_FK
		f.Target = fkRead
	case fkWrite != "":
		if section != "Write" {
			return f, fmt.Errorf("field %s: write reference in %s section", name, section)
		}
		f.Kind = KIND_FK
		f.Target = fkWrite
	case scalar != "":
		f.Kind = KIND_SCALAR
		f.Type = scalar
	default:
		f.Kind = KIND_ENUM
		f.Type = "Short Text"
		f.Enum = literals
	}
	return f, nil
}
