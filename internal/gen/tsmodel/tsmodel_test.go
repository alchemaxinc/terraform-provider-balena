const SAMPLE = `// These types were generated by @balena/abstract-sql-to-typescript v6.1.29

import type { Types } from '@balena/abstract-sql-to-typescript';

export interface Application {
	Read: {
		id: Types['Serial']['Read'];
		app_name: Types['Text']['Read'];
		is_of__class: 'fleet' | 'block' | 'app';
		should_be_running__release:
			{ __id: Release['Read']['id'] } | [Release['Read']] | [] | null;
		owns__release?: Array<Release['Read']>;
	};
	Write: {
		id: Types['Serial']['Write'];
		app_name: Types['Text']['Write'];
		is_of__class: 'fleet' | 'block' | 'app';
		should_be_running__release: Release['Write']['id'] | null;
	};
}

export interface Release {
	Read: {
		id: Types['Serial']['Read'];
		belongs_to__application:
			| { __id: Application['Read']['id'] }
			| [Application['Read']];
	};
	Write: Record<string, never>;
}

export default interface $Model {
	application: Application;
	release: Release;
	// Synonyms
	fleet_release: Release;
}
`

func TestParseSample(t *testing.T) {
	m, err := Parse(SAMPLE)
	if err != nil {
		t.Fatal(err)
	}
	if m.GeneratorVersion != "v6.1.29" {
		t.Errorf("GeneratorVersion = %q", m.GeneratorVersion)
	}
	app := m.Interfaces["Application"]
	if len(app.Read) != 5 || len(app.Write) != 4 {
		t.Fatalf("read=%d write=%d", len(app.Read), len(app.Write))
	}
	cases := map[string]Field{
		"app_name":                   {Name: "app_name", Kind: KIND_SCALAR, Type: "Text"},
		"is_of__class":               {Name: "is_of__class", Kind: KIND_ENUM, Type: "Short Text", Enum: []string{"fleet", "block", "app"}},
		"should_be_running__release": {Name: "should_be_running__release", Kind: KIND_FK, Target: "Release", Nullable: true},
		"owns__release":              {Name: "owns__release", Kind: KIND_REVERSE, Target: "Release", Optional: true},
	}
	for name, want := range cases {
		got, ok := app.ReadField(name)
		if !ok || got.Kind != want.Kind || got.Type != want.Type || got.Target != want.Target || got.Nullable != want.Nullable ||
			strings.Join(got.Enum, ",") != strings.Join(want.Enum, ",") {
			t.Errorf("%s = %+v, want %+v", name, got, want)
		}
	}
	if w, _ := app.WriteField("should_be_running__release"); w.Kind != KIND_FK || !w.Nullable {
		t.Errorf("write FK = %+v", w)
	}
	rel := m.Interfaces["Release"]
	if len(rel.Write) != 0 {
		t.Errorf("Record<string, never> should give no write fields")
	}
	if f, _ := rel.ReadField("belongs_to__application"); f.Kind != KIND_FK || f.Target != "Application" || f.Nullable {
		t.Errorf("leading-pipe union = %+v", f)
	}
	if name, _ := m.ResourceName("Release"); name != "fleet_release" {
		t.Errorf("ResourceName(Release) = %q", name)
	}
	if name, _ := m.ResourceName("Application"); name != "application" {
		t.Errorf("ResourceName(Application) = %q", name)
	}
}

func TestParseRejectsUnknownSyntax(t *testing.T) {
	bad := []string{
		strings.Replace(SAMPLE, "Types['Text']['Read']", "Partial<string>", 1),
		strings.Replace(SAMPLE, "export default interface $Model {", "export const x = 1;\nexport default interface $Model {", 1),
		strings.Replace(SAMPLE, "fleet_release: Release;", "fleet_release: Missing;", 1),
		strings.Replace(SAMPLE, "// These types were generated", "// Types generated", 1),
	}
	for i, src := range bad {
		if _, err := Parse(src); err == nil {
			t.Errorf("case %d: expected an error", i)
		}
	}
}

// MIN_RESOURCES are lower bounds for the roots vendored today, so a model that silently loses resources fails here.
// Any other root must have at least MIN_RESOURCES_ANY.
var MIN_RESOURCES = map[string]int{sources.ROOT_UNVERSIONED: 40, "v7": 60}

const MIN_RESOURCES_ANY = 40

// TestParseVendoredModels parses the model of every root in the lock, so a format change upstream fails here first.
// The roots a generation draws from (the default root and /resin) must parse. A newer root that does not parse
// blocks only its own promotion, which promote-root reports, so it is logged here.
func TestParseVendoredModels(t *testing.T) {
	const repo = "../../.."
	lock, err := sources.ReadLock(repo)
	if err != nil {
		t.Fatal(err)
	}
	files, err := lock.Files(repo)
	if err != nil {
		t.Fatal(err)
	}
	selected := map[string]bool{lock.DefaultRoot: true, sources.ROOT_UNVERSIONED: true}
	parsed := map[string]bool{}
	for _, r := range lock.Roots {
		m, err := Parse(string(files[r.Shape]))
		if err != nil {
			if selected[r.Name] {
				t.Errorf("root %s (%s): %v", r.Name, r.Shape, err)
			} else {
				t.Logf("root %s (%s) does not parse, which blocks only its promotion: %v", r.Name, r.Shape, err)
			}
			continue
		}
		parsed[r.Name] = true
		want, ok := MIN_RESOURCES[r.Name]
		if !ok {
			want = MIN_RESOURCES_ANY
		}
		if len(m.Canonical) < want {
			t.Errorf("root %s (%s): %d resources, want at least %d", r.Name, r.Shape, len(m.Canonical), want)
		}
	}
	for name := range selected {
		if !parsed[name] {
			t.Errorf("the lock selects root %s, which did not parse", name)
		}
	}
}

// TestParseKeepsLiteralsExactly checks that whitespace, separators and brackets inside string literals are kept as
// written, while whitespace between tokens still does not matter.
func TestParseKeepsLiteralsExactly(t *testing.T) {
	src := strings.Replace(SAMPLE, "\t\tis_of__class: 'fleet' | 'block' | 'app';\n\t\tshould_be_running__release:\n",
		"\t\t/** @experimental it's new */\n\t\tnote?: string;\n\t\tis_of__class:\n\t\t\t| 'fleet  one'\n\t\t\t| 'block\tx'\n\t\t\t| 'a;b'\n\t\t\t| 'c|d'\n\t\t\t| '{e'\n\t\t\t| ' f ';\n\t\tshould_be_running__release:\n", 1)
	if src == SAMPLE {
		t.Fatal("the sample did not change")
	}
	m, err := Parse(src)
	if err != nil {
		t.Fatal(err)
	}
	f, ok := m.Interfaces["Application"].ReadField("is_of__class")
	want := []string{"fleet  one", "block\tx", "a;b", "c|d", "{e", " f "}
	if !ok || f.Kind != KIND_ENUM || strings.Join(f.Enum, "\x00") != strings.Join(want, "\x00") {
		t.Errorf("is_of__class = %+v, want enum %q", f, want)
	}
	if n, ok := m.Interfaces["Application"].ReadField("note"); !ok || !n.Experimental {
		t.Errorf("note = %+v", n)
	}
	if got := normaliseSpace("a \t\n b 'x \t y'  \"p  q\"  "); got != "a b 'x \t y' \"p  q\"" {
		t.Errorf("normaliseSpace = %q", got)
	}
	for _, bad := range []string{"'open", "/* open"} {
		if _, err := parseFields("x: "+bad+";", "Read"); err == nil {
			t.Errorf("an unterminated %q must not parse", bad)
		}
	}
}
