package tsmodel

import (
	"os"
	"strings"
	"testing"
)

const SAMPLE = `// These types were generated by @balena/abstract-sql-to-typescript v6.1.29

import type { Types } from '@balena/abstract-sql-to-typescript';

export interface Application {
	Read: {
		id: Types['Serial']['Read'];
		app_name: Types['Text']['Read'];
		is_of__class: 'fleet' | 'block' | 'app';
		should_be_running__release:
			{ __id: Release['Read']['id'] } | [Release['Read']] | [] | null;
		owns__release?: Array<Release['Read']>;
	};
	Write: {
		id: Types['Serial']['Write'];
		app_name: Types['Text']['Write'];
		is_of__class: 'fleet' | 'block' | 'app';
		should_be_running__release: Release['Write']['id'] | null;
	};
}

export interface Release {
	Read: {
		id: Types['Serial']['Read'];
		belongs_to__application:
			| { __id: Application['Read']['id'] }
			| [Application['Read']];
	};
	Write: Record<string, never>;
}

export default interface $Model {
	application: Application;
	release: Release;
	// Synonyms
	fleet_release: Release;
}
`

func TestParseSample(t *testing.T) {
	m, err := Parse(SAMPLE)
	if err != nil {
		t.Fatal(err)
	}
	if m.GeneratorVersion != "v6.1.29" {
		t.Errorf("GeneratorVersion = %q", m.GeneratorVersion)
	}
	app := m.Interfaces["Application"]
	if len(app.Read) != 5 || len(app.Write) != 4 {
		t.Fatalf("read=%d write=%d", len(app.Read), len(app.Write))
	}
	cases := map[string]Field{
		"app_name":                   {Name: "app_name", Kind: KIND_SCALAR, Type: "Text"},
		"is_of__class":               {Name: "is_of__class", Kind: KIND_ENUM, Type: "Short Text", Enum: []string{"fleet", "block", "app"}},
		"should_be_running__release": {Name: "should_be_running__release", Kind: KIND_FK, Target: "Release", Nullable: true},
		"owns__release":              {Name: "owns__release", Kind: KIND_REVERSE, Target: "Release", Optional: true},
	}
	for name, want := range cases {
		got, ok := app.ReadField(name)
		if !ok || got.Kind != want.Kind || got.Type != want.Type || got.Target != want.Target || got.Nullable != want.Nullable ||
			strings.Join(got.Enum, ",") != strings.Join(want.Enum, ",") {
			t.Errorf("%s = %+v, want %+v", name, got, want)
		}
	}
	if w, _ := app.WriteField("should_be_running__release"); w.Kind != KIND_FK || !w.Nullable {
		t.Errorf("write FK = %+v", w)
	}
	rel := m.Interfaces["Release"]
	if len(rel.Write) != 0 {
		t.Errorf("Record<string, never> should give no write fields")
	}
	if f, _ := rel.ReadField("belongs_to__application"); f.Kind != KIND_FK || f.Target != "Application" || f.Nullable {
		t.Errorf("leading-pipe union = %+v", f)
	}
	if name, _ := m.ResourceName("Release"); name != "fleet_release" {
		t.Errorf("ResourceName(Release) = %q", name)
	}
	if name, _ := m.ResourceName("Application"); name != "application" {
		t.Errorf("ResourceName(Application) = %q", name)
	}
}

func TestParseRejectsUnknownSyntax(t *testing.T) {
	bad := []string{
		strings.Replace(SAMPLE, "Types['Text']['Read']", "Partial<string>", 1),
		strings.Replace(SAMPLE, "export default interface $Model {", "export const x = 1;\nexport default interface $Model {", 1),
		strings.Replace(SAMPLE, "fleet_release: Release;", "fleet_release: Missing;", 1),
		strings.Replace(SAMPLE, "// These types were generated", "// Types generated", 1),
	}
	for i, src := range bad {
		if _, err := Parse(src); err == nil {
			t.Errorf("case %d: expected an error", i)
		}
	}
}

// TestParseVendoredModels parses the vendored upstream models, so a format change upstream fails here first.
func TestParseVendoredModels(t *testing.T) {
	for path, minResources := range map[string]int{
		"../../../schema/upstream/open-balena-api/src/balena-model.ts": 40,
		"../../../schema/upstream/balena-sdk/src/types/v7.ts":          60,
	} {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		m, err := Parse(string(data))
		if err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		if len(m.Canonical) < minResources {
			t.Errorf("%s: %d resources", path, len(m.Canonical))
		}
	}
}
